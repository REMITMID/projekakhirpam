-- Skema Tabel Supabase untuk Koleksi Referensi

CREATE TABLE IF NOT EXISTS koleksi_referensi (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    judul TEXT NOT NULL,
    penulis TEXT NOT NULL,
    tahun_terbit TEXT NOT NULL,
    kategori TEXT NOT NULL,
    url_referensi TEXT NOT NULL,
    catatan TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Mengaktifkan Row Level Security (RLS) untuk keamanan data per pengguna
ALTER TABLE koleksi_referensi ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Pengguna dapat mengelola referensi sendiri"
    ON koleksi_referensi FOR ALL
    USING (auth.uid() = user_id)
    WITH CHECK (auth.uid() = user_id);
